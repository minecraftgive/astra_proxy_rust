//! Explicit generation/check command; ordinary tests never rewrite frontend sources.
use astra_management::v2::{Request, Response};
use ts_rs::{TypeVisitor, TS};
#[derive(Default)]
struct Contracts {
    seen: std::collections::HashSet<std::any::TypeId>,
    declarations: std::collections::BTreeMap<String, String>,
}
impl TypeVisitor for Contracts {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if !self.seen.insert(std::any::TypeId::of::<T>()) {
            return;
        }
        if T::output_path().is_some() {
            let cfg = ts_rs::Config::default();
            self.declarations.insert(T::ident(&cfg), T::decl(&cfg));
        }
        T::visit_dependencies(self);
    }
}
fn main() -> anyhow::Result<()> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../apps/web/src/generated/management.ts");
    let mut contracts = Contracts::default();
    contracts.visit::<Request>();
    contracts.visit::<Response>();
    let mut output = String::from(
        "// Generated by cargo run -p astra-management --features bindings --bin export-contracts. Do not edit.\n",
    );
    for declaration in contracts.declarations.values() {
        output.push_str("export ");
        for line in declaration.lines() {
            output.push_str(line.trim_end());
            output.push('\n');
        }
    }
    if std::env::args().any(|a| a == "--check") {
        anyhow::ensure!(
            std::fs::read_to_string(&path).ok().as_deref() == Some(output.as_str()),
            "TypeScript contract is stale; run export-contracts without --check"
        );
    } else {
        std::fs::create_dir_all(path.parent().unwrap())?;
        std::fs::write(path, output)?;
    }
    Ok(())
}
