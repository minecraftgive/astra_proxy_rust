import {test,expect} from '@playwright/test';

test('real authenticated nodes, shared drafts, server lifecycle and responsive views',async({page},testInfo)=>{
  test.skip(!process.env.ASTRA_E2E_URL||!process.env.ASTRA_E2E_PASSWORD,'Run through scripts/test.py management --browser with real TLS services');
  const failures:string[]=[];page.on('pageerror',error=>failures.push(error.message));
  await page.goto('/');await expect(page.getByRole('heading',{name:'登录管理控制台'})).toBeVisible();
  await page.getByLabel('管理员密码',{exact:true}).fill(process.env.ASTRA_E2E_PASSWORD!);
  const login=page.waitForResponse(r=>r.url().endsWith('/api/v2/login')&&r.status()===200);
  await page.getByRole('button',{name:'登录',exact:true}).click();const token=(await (await login).json()).token;
  const nodes=page.getByLabel('选择受控节点');await expect(nodes.locator('option')).toHaveCount(2);
  await nodes.selectOption('agent-a');await page.getByLabel('当前实例').selectOption({label:'proxy · 代理客户端'});
  await expect(page.getByRole('heading',{name:'proxy',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'停止实例',exact:true})).toBeEnabled();
  await page.screenshot({path:testInfo.outputPath('proxy-overview.png'),fullPage:true});
  await page.getByRole('button',{name:'编辑配置',exact:true}).click();
  const source=page.getByLabel('TOML 配置文档');await expect(source).toBeVisible();
  const original=await source.inputValue();const submitted=original+'\n# browser end-to-end save\n';
  await source.fill(submitted);await page.getByRole('button',{name:'保存并应用',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('配置保存完成');
  await page.getByRole('button',{name:'字段编辑',exact:true}).click();
  await expect(page.locator('.schema-field').first()).toBeVisible();
  await page.screenshot({path:testInfo.outputPath('shared-field-editor.png'),fullPage:true});
  await page.getByRole('button',{name:'TOML',exact:true}).click();await expect(source).toHaveValue(submitted);
  await source.fill(submitted+'# retained in browser without changing disk\n');
  await nodes.selectOption('agent-b');await page.getByLabel('当前实例').selectOption({label:'server · 代理服务端'});
  await expect(page.getByRole('heading',{name:'server',exact:true})).toBeVisible();
  page.once('dialog',dialog=>dialog.accept());await page.getByRole('button',{name:'停止实例',exact:true}).click();
  await expect(page.getByRole('button',{name:'启动实例',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'启动实例',exact:true}).click();await expect(page.getByRole('button',{name:'停止实例',exact:true})).toBeEnabled();
  await page.screenshot({path:testInfo.outputPath('server-overview.png'),fullPage:true});
  await nodes.selectOption('agent-a');await page.getByLabel('当前实例').selectOption({label:'proxy · 代理客户端'});
  await page.getByRole('button',{name:'编辑配置',exact:true}).click();
  await expect(page.getByText('此浏览器保留了尚未同步的编辑内容。')).toBeVisible();
  await page.getByRole('button',{name:'恢复内容',exact:true}).click();await expect(source).toHaveValue(submitted+'# retained in browser without changing disk\n');
  await page.getByRole('button',{name:'返回',exact:true}).click();
  await page.setViewportSize({width:740,height:900});
  await page.screenshot({path:testInfo.outputPath('compact-overview.png'),fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect(await page.evaluate(()=>JSON.stringify({...localStorage}))).not.toContain(token);
  await page.getByRole('button',{name:'退出登录',exact:true}).click();await expect(page.getByRole('heading',{name:'登录管理控制台'})).toBeVisible();
  expect(failures).toEqual([]);
});
