"""Generate build metadata watches from local normal/build dependency closures.

No Cargo subprocess, downloads, or toolchain are needed. Dev dependencies are
excluded; optional and target-specific production dependencies are conservatively
included, so the same checked-in table supports every native target and feature.
"""
from pathlib import Path
import tomllib


# astra-platform embeds these GUI assets in native installation entries. They
# are outside its manifest dependency tree; watch the files, not all GUI code.
EMBEDDED_INPUTS = {
    'astra-platform': (
        'crates/astra-gui/assets/icon.svg',
        'crates/astra-gui/assets/icon.icns',
    ),
}


def dependency_sections(manifest):
    yield manifest.get('dependencies', {})
    yield manifest.get('build-dependencies', {})
    for target in manifest.get('target', {}).values():
        yield target.get('dependencies', {})
        yield target.get('build-dependencies', {})


def input_table(root):
    root = Path(root).resolve()
    workspace = tomllib.loads((root / 'Cargo.toml').read_text())
    patches = workspace.get('patch', {}).get('crates-io', {})
    packages = {}
    pending = [root / member for member in workspace['workspace']['members']]
    pending += [root / spec['path'] for spec in patches.values() if 'path' in spec]
    while pending:
        directory = pending.pop().resolve()
        if directory in packages:
            continue
        data = tomllib.loads((directory / 'Cargo.toml').read_text())
        dependencies = set()
        for section in dependency_sections(data):
            for name, spec in section.items():
                spec = spec if isinstance(spec, dict) else {}
                path_base = directory
                if spec.get('workspace'):
                    shared = workspace.get('workspace', {}).get('dependencies', {}).get(name, {})
                    spec = {**(shared if isinstance(shared, dict) else {}), **spec}
                    path_base = root
                patch = patches.get(spec.get('package', name), {})
                path = ((path_base / spec['path']) if 'path' in spec else
                        (root / patch['path']) if 'path' in patch else None)
                if path is not None:
                    path = path.resolve()
                    path.relative_to(root)  # Reject external paths in a portable table.
                    dependencies.add(path)
                    pending.append(path)
        packages[directory] = (data['package']['name'], dependencies)

    def closure(directory, seen=None):
        seen = set() if seen is None else seen
        if directory not in seen:
            seen.add(directory)
            for dependency in packages[directory][1]:
                closure(dependency, seen)
        return seen

    def watched_paths(directory):
        dependencies = closure(directory)
        paths = {path.relative_to(root).as_posix() for path in dependencies}
        for dependency in dependencies:
            paths.update(EMBEDDED_INPUTS.get(packages[dependency][0], ()))
        return sorted(paths)

    return {name: watched_paths(directory)
            for directory, (name, _) in packages.items()
            if (directory / 'build.rs').is_file()
            and 'build_metadata.rs' in (directory / 'build.rs').read_text()}


def render_inputs(root):
    lines = ['// Generated by python scripts/build_metadata_inputs.py. Do not edit.',
             'const LOCAL_METADATA_INPUTS: &[(&str, &[&str])] = &[']
    for name, paths in sorted(input_table(root).items()):
        lines.append(f'    ("{name}", &[')
        lines.extend(f'        "{path}",' for path in paths)
        lines.append('    ]),')
    return '\n'.join([*lines, '];', ''])
